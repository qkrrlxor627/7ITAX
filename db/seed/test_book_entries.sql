-- 세목별 집계 확인
SELECT category_name, entry_type,
       COUNT(*) AS 건수,
       SUM(income_amount) AS 수입합계,
       SUM(expense_amount) AS 경비합계,
       SUM(fixed_asset_amount) AS 자산합계,
       SUM(vat_amount) AS VAT합계,
       is_business_expense, is_vat_deductible
FROM book_entries
WHERE user_id = 1 AND EXTRACT(YEAR FROM entry_date) = 2025
GROUP BY category_name, entry_type, is_business_expense, is_vat_deductible
ORDER BY entry_type, category_name;

-- 소득세 필요경비 합계 (businessExpense만)
SELECT '소득세 필요경비' AS 항목,
       SUM(expense_amount) AS 금액
FROM book_entries
WHERE user_id = 1 AND confirmed = TRUE
  AND entry_type = 'EXPENSE' AND is_business_expense = TRUE
  AND entry_date BETWEEN '2025-01-01' AND '2025-12-31';

-- 부가세 1기 매출세액 / 매입세액(공제)
SELECT '부가세 1기 매출세액' AS 항목,
       SUM(vat_amount) AS 금액
FROM book_entries
WHERE user_id = 1 AND confirmed = TRUE AND entry_type = 'INCOME'
  AND entry_date BETWEEN '2025-01-01' AND '2025-06-30'
UNION ALL
SELECT '부가세 1기 매입세액(공제)',
       SUM(vat_amount)
FROM book_entries
WHERE user_id = 1 AND confirmed = TRUE AND entry_type = 'EXPENSE'
  AND is_business_expense = TRUE AND is_vat_deductible = TRUE
  AND entry_date BETWEEN '2025-01-01' AND '2025-06-30';
