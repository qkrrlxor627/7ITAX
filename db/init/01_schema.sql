    business_reg_number VARCHAR(512),
    industry_code       VARCHAR(255),
    nts_verified        BOOLEAN     NOT NULL,
    nts_verified_at     TIMESTAMP(6),
    user_id             BIGINT      NOT NULL UNIQUE,
    CONSTRAINT fk_bp_user FOREIGN KEY (user_id) REFERENCES users(id)
);

-- ============================================================
-- 3. user_consents
-- ============================================================
CREATE TABLE IF NOT EXISTS user_consents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),
    consent_type    VARCHAR(255) NOT NULL
                        CHECK (consent_type IN ('SERVICE', 'PRIVACY', 'FINANCIAL')),
    consented       BOOLEAN      NOT NULL,
    consented_at    TIMESTAMP(6),
    revoked_at      TIMESTAMP(6),
    user_id         BIGINT       NOT NULL,
    CONSTRAINT uq_user_consent UNIQUE (user_id, consent_type),
    CONSTRAINT fk_uc_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_consent_user_id ON user_consents (user_id);

-- ============================================================
-- 4. cards
-- ============================================================
CREATE TABLE IF NOT EXISTS cards (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMP(6),
    updated_at              TIMESTAMP(6),
    card_expiry_date        VARCHAR(255),
    card_name               VARCHAR(255) NOT NULL,
    card_no                 VARCHAR(512) NOT NULL,
    card_type               VARCHAR(255) NOT NULL
                                CHECK (card_type IN ('PERSONAL', 'BUSINESS')),
    card_unique_no          VARCHAR(255) NOT NULL,
    cvc                     VARCHAR(512) NOT NULL,
    deleted                 BOOLEAN      NOT NULL,
    is_default              BOOLEAN      NOT NULL,
    last4digits             VARCHAR(4)   NOT NULL,
    withdrawal_account_no   VARCHAR(255),
    withdrawal_date         VARCHAR(255),
    user_id                 BIGINT       NOT NULL,
    CONSTRAINT fk_card_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_card_user_id ON cards (user_id);

-- ============================================================
-- 5. card_transactions
-- ============================================================
CREATE TABLE IF NOT EXISTS card_transactions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMP(6),
    updated_at          TIMESTAMP(6),
    amount              BIGINT       NOT NULL,
    balance_after       BIGINT       NOT NULL,
    description         VARCHAR(255),
    transaction_type    VARCHAR(255) NOT NULL
                            CHECK (transaction_type IN ('CHARGE', 'PAYMENT', 'REFUND')),
    card_id             BIGINT       NOT NULL,
