-- ============================================================
-- 6. payments
-- ============================================================
CREATE TABLE IF NOT EXISTS payments (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                  TIMESTAMP(6),
    updated_at                  TIMESTAMP(6),
    amount                      BIGINT       NOT NULL,
    authorization_code          VARCHAR(255),
    authorized_at               TIMESTAMP(6),
    cancel_reason               VARCHAR(255),
    cancelled_amount            BIGINT,
    cancelled_at                TIMESTAMP(6),
    captured_at                 TIMESTAMP(6),
    currency                    VARCHAR(255) NOT NULL,
    merchant_category_code      VARCHAR(255),
    merchant_id                 BIGINT,
    merchant_name               VARCHAR(255) NOT NULL,
    payment_method              VARCHAR(255) NOT NULL
                                    CHECK (payment_method IN ('ONLINE', 'OFFLINE')),
    purpose                     VARCHAR(255) NOT NULL
                                    CHECK (purpose IN ('PERSONAL', 'BUSINESS')),
    ssafy_transaction_unique_no BIGINT,
    status                      VARCHAR(255) NOT NULL
                                    CHECK (status IN ('AUTHORIZED', 'CAPTURED', 'CANCELLED', 'DECLINED')),
    card_id                     BIGINT       NOT NULL,
    user_id                     BIGINT       NOT NULL,
    CONSTRAINT fk_pay_card FOREIGN KEY (card_id) REFERENCES cards(id),
    CONSTRAINT fk_pay_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_payment_user_id     ON payments (user_id);
CREATE INDEX IF NOT EXISTS idx_payment_card_id     ON payments (card_id);
CREATE INDEX IF NOT EXISTS idx_payment_status      ON payments (status);
CREATE INDEX IF NOT EXISTS idx_payment_user_status ON payments (user_id, status);

-- ============================================================
-- 7. transfers
-- ============================================================
CREATE TABLE IF NOT EXISTS transfers (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                  TIMESTAMP(6),
    updated_at                  TIMESTAMP(6),
    amount                      BIGINT       NOT NULL,
    description                 VARCHAR(255),
    ssafy_transaction_unique_no VARCHAR(255),
    status                      VARCHAR(255) NOT NULL
                                    CHECK (status IN ('COMPLETED', 'FAILED')),
    target_account_no           VARCHAR(255),
    transfer_type               VARCHAR(255) NOT NULL
                                    CHECK (transfer_type IN ('P2P', 'WITHDRAW')),
    receiver_card_id            BIGINT,
    receiver_user_id            BIGINT,
    sender_card_id              BIGINT       NOT NULL,
    sender_user_id              BIGINT       NOT NULL,
    CONSTRAINT fk_tf_sender_card   FOREIGN KEY (sender_card_id)   REFERENCES cards(id),
    CONSTRAINT fk_tf_sender_user   FOREIGN KEY (sender_user_id)   REFERENCES users(id),
    CONSTRAINT fk_tf_receiver_card FOREIGN KEY (receiver_card_id) REFERENCES cards(id),
    CONSTRAINT fk_tf_receiver_user FOREIGN KEY (receiver_user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_transfer_sender_user   ON transfers (sender_user_id);
CREATE INDEX IF NOT EXISTS idx_transfer_receiver_user ON transfers (receiver_user_id);

