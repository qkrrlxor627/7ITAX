-- ============================================================
-- 1. users
-- ============================================================
CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),
    biometric_enabled BOOLEAN     NOT NULL,
    birth_date      DATE,
    ci              VARCHAR(128) NOT NULL UNIQUE,
    device_id       VARCHAR(255),
    di              VARCHAR(128) NOT NULL UNIQUE,
    gender          VARCHAR(255),
    is_business     BOOLEAN      NOT NULL,
    kyc_verified    BOOLEAN      NOT NULL,
    last_login_at   TIMESTAMP(6),
    name            VARCHAR(512),
    phone_last4     VARCHAR(4),
    phone_number    VARCHAR(512),
    pin_hash        VARCHAR(200),
    pay_pin_hash    VARCHAR(200),
    ssafy_user_key  VARCHAR(100),
    status          VARCHAR(255) NOT NULL
                        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

CREATE INDEX IF NOT EXISTS idx_user_phone_last4 ON users (phone_last4);

-- ============================================================
-- 2. business_profiles
