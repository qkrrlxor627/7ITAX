-- ============================================================
-- 15. mcc_tax_rule (MCC -> 세목 매핑 룰)
-- ============================================================
CREATE TABLE IF NOT EXISTS mcc_tax_rule (
    id                    BIGSERIAL       PRIMARY KEY,
    mcc                   VARCHAR(10)     NOT NULL,
    tier                  VARCHAR(1)      NOT NULL CHECK (tier IN ('A', 'B')),
    condition_expr        TEXT,
    tax_category          VARCHAR(50)     NOT NULL,
    vat_deductible        VARCHAR(30)     NOT NULL DEFAULT '확인필요',
    amount_threshold      BIGINT,
    remark                TEXT,
    legal_basis           VARCHAR(200),
    annual_limit          BIGINT,
    confidence            INTEGER,
    requires_user_confirm BOOLEAN         NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ     NOT NULL DEFAULT now()
);

CREATE INDEX  IF NOT EXISTS idx_mcc_tax_rule_mcc ON mcc_tax_rule (mcc);
CREATE INDEX  IF NOT EXISTS idx_mcc_tax_rule_tier ON mcc_tax_rule (tier);
CREATE UNIQUE INDEX IF NOT EXISTS uq_mcc_tax_rule_mcc_condition ON mcc_tax_rule (mcc, COALESCE(condition_expr, ''));

